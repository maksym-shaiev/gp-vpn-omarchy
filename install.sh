#!/usr/bin/env bash
# install.sh — gp-vpn-omarchy installer
#
# Installs the GlobalProtect (openconnect-based) Omarchy bar widget.
#
# What this script does:
#   1. Detects Omarchy (requires omarchy-shell on PATH)
#   2. Prompts for portal / connection name / browser when no existing config
#      is found (so the widget can read CONN_NAME + PORTAL from
#      ~/.config/smc-gp-vpn/config — the same format smc-gp-vpn writes).
#   3. Warns if smc-vpn-refresh / gpclient-smc are missing (Refresh/Reconnect
#      buttons need them; status/toggle still work without).
#   4. Copies the plugin files to ~/.config/omarchy/plugins/gp-vpn/
#   5. Rescans plugins and enables gp-vpn (bar placement from manifest
#      defaultSection: "right").
#   6. Prints the hotkey line to paste into ~/.config/hypr/bindings.lua.
#
# Usage:
#   bash install.sh
#
# Supported: Omarchy (Arch-based distributions with omarchy-shell installed).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SMC_CONFIG_FILE="$HOME/.config/smc-gp-vpn/config"
PLUGINS_DIR="$HOME/.config/omarchy/plugins"
PLUGIN_ID="gp-vpn"
TARGET_DIR="$PLUGINS_DIR/$PLUGIN_ID"

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
BOLD='\033[1m'; RESET='\033[0m'

info()    { echo -e "${GREEN}[+]${RESET} $*"; }
warn()    { echo -e "${YELLOW}[!]${RESET} $*"; }
error()   { echo -e "${RED}[✗]${RESET} $*" >&2; }
die()     { error "$*"; exit 1; }
section() { echo -e "\n${BOLD}── $* ──${RESET}"; }

# ── 1. detect Omarchy ────────────────────────────────────────────────────────
section "Checking prerequisites"

if ! command -v omarchy-shell &>/dev/null; then
    die "This installer is for Omarchy only (omarchy-shell not found on PATH)."
fi

if ! command -v omarchy-plugin-enable &>/dev/null; then
    die "omarchy-plugin-enable not found on PATH."
fi

info "Detected: Omarchy"

# ── 2. configuration ─────────────────────────────────────────────────────────
section "Configuration"

prompt() {
    local var="$1" prompt="$2" default="$3"
    read -rp "  ${prompt} [${default}]: " value
    value="${value:-$default}"
    printf -v "$var" '%s' "$value"
}

if [[ -r "$SMC_CONFIG_FILE" ]]; then
    info "Using existing config at $SMC_CONFIG_FILE"
    SMC_PORTAL=$(awk -F= '$1=="PORTAL"{print $2}' "$SMC_CONFIG_FILE")
    SMC_CONN=$(awk -F= '$1=="CONN_NAME"{print $2}' "$SMC_CONFIG_FILE")
    SMC_BROWSER=$(awk -F= '$1=="BROWSER"{print $2}' "$SMC_CONFIG_FILE")
    info "Portal:    ${SMC_PORTAL:-<not set>}"
    info "Connection: ${SMC_CONN:-<not set>}"
    info "Browser:   ${SMC_BROWSER:-<not set>}"
else
    prompt PORTAL    "Portal gateway (e.g. us-access.stagwellglobal.com)" ""
    if [[ -z "$PORTAL" ]]; then
        die "Portal is required."
    fi
    prompt CONN_NAME "NM connection name" "SMC"
    prompt BROWSER   "Browser for CAS auth" "chrome"

    SMC_CONFIG_DIR="$(dirname "$SMC_CONFIG_FILE")"
    mkdir -p "$SMC_CONFIG_DIR"
    chmod 700 "$SMC_CONFIG_DIR"

    cat > "$SMC_CONFIG_FILE" <<EOF
# smc-gp-vpn configuration
# Generated by gp-vpn-omarchy install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)

PORTAL=$PORTAL
CONN_NAME=$CONN_NAME
BROWSER=$BROWSER
GPCLIENT_BIN=$HOME/.local/bin/gpclient-smc
GP_AUTH_BIN=$HOME/.local/bin/gpauth-smc
CACHE=$HOME/.config/gpclient/smc-cookie.json
EOF
    chmod 600 "$SMC_CONFIG_FILE"
    info "Config written to $SMC_CONFIG_FILE"
fi

# ── 3. prerequisites ─────────────────────────────────────────────────────────
section "Checking VPN prerequisites"

MISSING=()
for cmd in smc-vpn-refresh gpclient-smc; do
    if ! command -v "$cmd" &>/dev/null; then
        MISSING+=("$cmd")
    fi
done

if [[ ${#MISSING[@]} -gt 0 ]]; then
    warn "Missing VPN prerequisites:"
    for m in "${MISSING[@]}"; do echo "    • $m"; done
    warn "The widget's Refresh/Reconnect buttons need these."
    warn "Status and toggle still work without them."
else
    info "All VPN prerequisites satisfied"
fi

# ── 4. install plugin files ──────────────────────────────────────────────────
section "Installing plugin files"

mkdir -p "$TARGET_DIR"

for f in manifest.json Panel.qml gp-vpn-status; do
    install -m 644 "$SCRIPT_DIR/$f" "$TARGET_DIR/$f"
done
chmod +x "$TARGET_DIR/gp-vpn-status"
info "Installed plugin files to $TARGET_DIR"

# ── 5. enable plugin ─────────────────────────────────────────────────────────
section "Enabling plugin"

omarchy-shell shell rescanPlugins >/dev/null
omarchy-plugin-enable "$PLUGIN_ID"
info "Plugin enabled"

# ── 6. hotkey hint ───────────────────────────────────────────────────────────
section "Next steps"

cat <<EOF

${BOLD}Add a global hotkey${RESET} to open the popup anywhere:

    ${GREEN}o.bind("SUPER + ALT + V", "GlobalProtect VPN", "omarchy-shell -q shell toggle gp-vpn")${RESET}

Paste the line above into ~/.config/hypr/bindings.lua and run:

    ${GREEN}hyprctl reload${RESET}

${BOLD}Done.${RESET}
EOF
